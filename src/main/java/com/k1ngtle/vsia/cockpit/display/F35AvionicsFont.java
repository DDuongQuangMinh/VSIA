    private F35AvionicsFont() {
    }

    public static void draw(
            F35DisplayCanvas canvas,
            String text,
            float x,
            float y,
            float scale,
            int color
    ) {
        if (text == null
                || text.isEmpty()) {
            return;
        }

        String normalized =
                text.toUpperCase(
                        Locale.ROOT
                );

        float cursor =
                x;

        for (int i = 0;
             i < normalized.length();
             i++) {
            char character =
                    normalized.charAt(
                            i
                    );

            int[] rows =
                    GLYPHS.getOrDefault(
                            character,
                            GLYPHS.get(
                                    '?'
                            )
                    );

            drawGlyph(
                    canvas,
                    rows,
                    cursor,
                    y,
                    scale,
                    color
            );

            cursor +=
                    (
                            GLYPH_WIDTH + 1
                    )
                            * scale;
        }
    }

    public static float width(
            String text,
            float scale
    ) {
        if (text == null
                || text.isEmpty()) {
            return 0.0F;
        }

        return (
                text.length()
                        * (
                        GLYPH_WIDTH + 1
                )
                        - 1
        )
                * scale;
    }

    public static float height(
            float scale
    ) {
        return GLYPH_HEIGHT
                * scale;
    }

    private static void drawGlyph(
            F35DisplayCanvas canvas,
            int[] rows,
            float x,
            float y,
            float scale,
            int color
    ) {
        for (int row = 0;
             row < GLYPH_HEIGHT;
             row++) {
            int bits =
                    rows[row];

            int start =
                    -1;

            for (int column = 0;
                 column <= GLYPH_WIDTH;
                 column++) {
                boolean on =
                        column < GLYPH_WIDTH
                                && (
                                bits
                                        & (
                                        1
                                                << (
                                                GLYPH_WIDTH
                                                        - 1
                                                        - column
                                        )
                                )
                        )
                                != 0;

                if (on
                        && start < 0) {
                    start =
                            column;
                }

                if (!on
                        && start >= 0) {
                    float x1 =
                            x
                                    + start
                                    * scale;

                    float x2 =
                            x
                                    + column
                                    * scale
                                    - scale
                                    * 0.15F;

                    float yy =
                            y
                                    + row
                                    * scale;

                    canvas.line(
                            x1,
                            yy,
                            x2,
                            yy,
                            color
                    );

                    start =
                            -1;
                }
            }
        }
    }

    private static void put(
            char character,
            String... rows
    ) {
        int[] encoded =
                new int[GLYPH_HEIGHT];

        for (int row = 0;
             row < GLYPH_HEIGHT;
             row++) {
            int bits =
                    0;

            for (int column = 0;
                 column < GLYPH_WIDTH;
                 column++) {
                bits <<= 1;

                if (rows[row]
                        .charAt(
                                column
                        )
                        == '1') {
                    bits |= 1;
                }
            }

            encoded[row] =
                    bits;
        }

        GLYPHS.put(
                character,
                encoded
        );
    }
